import { test, expect } from '@playwright/test'

test('explanation appears only after selection and supports close, reopen and deselect', async ({page}) => {
  await page.goto('/')
  const candidate=page.getByTestId('candidate-0')
  const inspector=page.getByRole('complementary',{name:'Bằng chứng gợi ý'})
  await expect(candidate).toBeVisible()
  await expect(inspector).toHaveCount(0)
  await candidate.click()
  await expect(inspector).toBeVisible()
  const oldTimeline=(await page.locator('.timeline').boundingBox())!.y
  await page.getByRole('button',{name:/Thu gọn toàn bộ/}).click()
  await expect(inspector.locator('#inspector-body')).toHaveCount(0)
  expect((await inspector.boundingBox())!.height).toBeLessThan(100)
  expect((await page.locator('.timeline').boundingBox())!.y).toBeLessThan(oldTimeline)
  await page.getByRole('button',{name:/Mở rộng/}).click()
  await expect(inspector.locator('#inspector-body')).toBeVisible()
  expect((await inspector.boundingBox())!.height).toBeGreaterThan(100)
  await page.getByRole('button',{name:'Đóng hiểu lựa chọn'}).click()
  await expect(inspector).toHaveCount(0)
  await page.getByRole('button',{name:'Mở hiểu lựa chọn'}).click()
  await expect(inspector).toBeVisible()
  await candidate.click()
  await expect(inspector).toHaveCount(0)
  await expect(page.getByRole('button',{name:'Mở hiểu lựa chọn'})).toHaveCount(0)
  await expect(page.locator('.recommendations .primary')).toBeDisabled()
  const manual=page.getByRole('region',{name:'Chọn tướng thủ công'})
  await manual.getByLabel('Tìm tướng').fill('Ahri')
  const ahri=manual.getByRole('button',{name:'Ahri',exact:true})
  await ahri.click()
  await expect(inspector).toContainText('Ahri')
  await ahri.click()
  await expect(inspector).toHaveCount(0)
  await candidate.click()
  const response=page.waitForResponse(r=>r.url().endsWith('/api/draft/action'))
  await page.locator('.recommendations .primary').click()
  expect((await response).status()).toBe(200)
  await expect(inspector).toHaveCount(0)
  await page.reload()
  await expect(candidate).toBeVisible()
  await expect(inspector).toHaveCount(0)
})
