import { test, expect } from '@playwright/test'
import { mkdir } from 'node:fs/promises'

test('centered original vertical team boards preserve surrounding layout', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByTestId('candidate-0')).toBeVisible()
  const boards = await page.locator('.teams-grid').boundingBox()
  const workspace = await page.locator('.workspace').boundingBox()
  expect(Math.abs(boards!.x + boards!.width / 2 - workspace!.x - workspace!.width / 2)).toBeLessThan(2)
  expect(boards!.width).toBeLessThanOrEqual(1001)
  const top = await page.getByTestId('slot-blue-top').boundingBox()
  const mid = await page.getByTestId('slot-blue-mid').boundingBox()
  expect(Math.abs(top!.x - mid!.x)).toBeLessThan(2)
  expect(mid!.y).toBeGreaterThan(top!.y + top!.height)
  const left = await page.locator('.recommendations').boundingBox()
  const right = await page.locator('.manual-choice').boundingBox()
  expect(Math.abs(left!.y - right!.y)).toBeLessThan(2)
  expect(left!.x).toBeLessThan(right!.x)
  expect(Math.abs(left!.y - boards!.y)).toBeLessThan(2)
  expect(left!.x + left!.width).toBeLessThan(boards!.x)
  expect(boards!.x + boards!.width).toBeLessThan(right!.x)
  await expect(page.locator('.inspector')).toHaveCount(0)
  await page.getByTestId('candidate-0').click()
  const inspector = await page.locator('.inspector').boundingBox()
  expect(inspector!.y).toBeGreaterThanOrEqual(left!.y + left!.height)
  await mkdir('../reports/ui_sidebars_fit', {recursive:true})
  for (const width of [900,1024,1100,1199,1366,1553,1920]) {
    await page.setViewportSize({width,height:1000})
    const box = await page.locator('.teams-grid').boundingBox()
    const a = await page.locator('.recommendations').boundingBox()
    const b = await page.locator('.manual-choice').boundingBox()
    expect(Math.abs(a!.y-box!.y)).toBeLessThan(2)
    expect(Math.abs(b!.y-box!.y)).toBeLessThan(2)
    expect(a!.x+a!.width).toBeLessThan(box!.x)
    expect(box!.x+box!.width).toBeLessThan(b!.x)
    expect(Math.abs(a!.height-box!.height)).toBeLessThan(2)
    expect(Math.abs(b!.height-box!.height)).toBeLessThan(2)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  }
  await page.setViewportSize({width:1553,height:1000})
  await page.screenshot({path:'../reports/ui_inspector_toggle/desktop.png',fullPage:true})
  await page.setViewportSize({width:390,height:844})
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({path:'../reports/ui_inspector_toggle/mobile.png',fullPage:true})
})
